"""Small server-side session gate for the LAN Roteiro Live surface."""

from __future__ import annotations

import base64
import hashlib
import hmac
import os
import secrets
import threading
import time
from dataclasses import dataclass


SESSION_COOKIE = "celia_roteiro_session"
PASSWORD_HASH_ENV = "CELIA_ROTEIRO_PASSWORD_HASH"
SESSION_TTL_ENV = "CELIA_ROTEIRO_SESSION_TTL_SECONDS"
MAX_FAILURES_ENV = "CELIA_ROTEIRO_MAX_LOGIN_FAILURES"
COOLDOWN_ENV = "CELIA_ROTEIRO_LOGIN_COOLDOWN_SECONDS"


def _int_env(name: str, default: int, minimum: int, maximum: int) -> int:
    try:
        value = int(os.getenv(name, str(default)))
    except (TypeError, ValueError):
        return default
    return max(minimum, min(maximum, value))


def _b64decode(value: str) -> bytes:
    return base64.urlsafe_b64decode(value.encode("ascii") + b"=" * (-len(value) % 4))


def _b64encode(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).decode("ascii").rstrip("=")


def hash_password(password: str) -> str:
    """Create the deployable scrypt format without ever logging the password."""
    if not password:
        raise ValueError("password must not be empty")
    salt = secrets.token_bytes(16)
    n, r, p = 16384, 8, 1
    digest = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=n, r=r, p=p, dklen=32)
    return f"scrypt${n}${r}${p}${_b64encode(salt)}${_b64encode(digest)}"


def verify_password(password: str, encoded: str) -> bool:
    """Verify only the scrypt format generated by :func:`hash_password`."""
    if not password or not encoded:
        return False
    try:
        scheme, raw_n, raw_r, raw_p, raw_salt, raw_digest = encoded.split("$", 5)
        if scheme != "scrypt":
            return False
        n, r, p = int(raw_n), int(raw_r), int(raw_p)
        if n < 16384 or n > 262144 or r < 1 or r > 32 or p < 1 or p > 8:
            return False
        salt = _b64decode(raw_salt)
        expected = _b64decode(raw_digest)
        actual = hashlib.scrypt(
            password.encode("utf-8"), salt=salt, n=n, r=r, p=p, dklen=len(expected)
        )
    except (ValueError, TypeError, UnicodeError):
        return False
    return hmac.compare_digest(actual, expected)


@dataclass(frozen=True)
class LoginDecision:
    allowed: bool
    retry_after: int = 0


class RoteiroAuth:
    """In-memory sessions and bounded login failures for one Célia process."""

    def __init__(self) -> None:
        self.session_ttl = _int_env(SESSION_TTL_ENV, 8 * 60 * 60, 300, 7 * 24 * 60 * 60)
        self.max_failures = _int_env(MAX_FAILURES_ENV, 5, 2, 20)
        self.cooldown_seconds = _int_env(COOLDOWN_ENV, 30, 5, 3600)
        self._sessions: dict[str, float] = {}
        self._failures: dict[str, list[float]] = {}
        self._lock = threading.Lock()

    @property
    def configured(self) -> bool:
        encoded = os.getenv(PASSWORD_HASH_ENV, "").strip()
        return bool(encoded and encoded.startswith("scrypt$"))

    def _prune(self, now: float) -> None:
        self._sessions = {token: expiry for token, expiry in self._sessions.items() if expiry > now}
        cutoff = now - self.cooldown_seconds
        self._failures = {
            ip: [stamp for stamp in stamps if stamp > cutoff]
            for ip, stamps in self._failures.items()
            if any(stamp > cutoff for stamp in stamps)
        }

    def login_allowed(self, client_ip: str) -> LoginDecision:
        now = time.monotonic()
        with self._lock:
            self._prune(now)
            stamps = self._failures.get(client_ip, [])
            if len(stamps) < self.max_failures:
                return LoginDecision(True)
            retry_after = max(1, int(self.cooldown_seconds - (now - stamps[0])))
            return LoginDecision(False, retry_after)

    def record_failure(self, client_ip: str) -> None:
        now = time.monotonic()
        with self._lock:
            self._prune(now)
            self._failures.setdefault(client_ip, []).append(now)

    def clear_failures(self, client_ip: str) -> None:
        with self._lock:
            self._failures.pop(client_ip, None)

    def authenticate(self, password: str, client_ip: str) -> bool:
        decision = self.login_allowed(client_ip)
        if not decision.allowed:
            return False
        encoded = os.getenv(PASSWORD_HASH_ENV, "").strip()
        if not self.configured or not verify_password(password, encoded):
            self.record_failure(client_ip)
            return False
        self.clear_failures(client_ip)
        return True

    def create_session(self) -> str:
        token = secrets.token_urlsafe(32)
        with self._lock:
            self._prune(time.monotonic())
            self._sessions[token] = time.monotonic() + self.session_ttl
        return token

    def valid_session(self, token: str | None) -> bool:
        if not token:
            return False
        now = time.monotonic()
        with self._lock:
            self._prune(now)
            expiry = self._sessions.get(token)
            return bool(expiry and expiry > now)

    def revoke(self, token: str | None) -> None:
        if token:
            with self._lock:
                self._sessions.pop(token, None)


roteiro_auth = RoteiroAuth()
